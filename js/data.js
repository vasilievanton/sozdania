/* ============================================================
   Утилиты для прототипа
   ============================================================ */

const TODAY_FAKE = '2026-06-05'; // "сегодня" в прототипе — начало проекта

function isOpenOn(release, dateStr) {
  const d = dateStr || TODAY_FAKE;
  if (release.from && d < release.from) return false;
  if (release.to   && d > release.to)   return false;
  return true;
}

function releasesFor(kind, dateStr) {
  return SCHEDULE.filter(r => r.kind === kind && isOpenOn(r, dateStr));
}

function upcomingFor(kind, dateStr) {
  const d = dateStr || TODAY_FAKE;
  return SCHEDULE.filter(r => r.kind === kind && r.from && r.from > d);
}

function fmtRu(dateStr) {
  const [, m, dd] = dateStr.split('-');
  const months = ['', 'янв','фев','мар','апр','мая','июня','июля','авг','сен','окт','ноя','дек'];
  return `${parseInt(dd,10)} ${months[parseInt(m,10)]}`;
}

